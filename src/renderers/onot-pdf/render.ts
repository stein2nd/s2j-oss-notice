import { TOOL_VERSION } from "../../compat/tool-version.js";
import type { ExtractedLicense, NoticeDocument } from "../../types/notice.js";
import { onotFooterLines } from "../onot-shared/footer.js";
import { buildLicenseBlocks, componentsRows } from "../onot-shared/licenses.js";

function escapePdfText(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

function wrapLines(text: string, maxChars: number): string[] {
  const lines: string[] = [];
  for (const paragraph of text.split(/\r?\n/)) {
    if (paragraph.length === 0) {
      lines.push("");
      continue;
    }
    let rest = paragraph;
    while (rest.length > maxChars) {
      let split = rest.lastIndexOf(" ", maxChars);
      if (split < maxChars * 0.5) {
        split = maxChars;
      }
      lines.push(rest.slice(0, split).trimEnd());
      rest = rest.slice(split).trimStart();
    }
    if (rest.length > 0) {
      lines.push(rest);
    }
  }
  return lines;
}

function buildStructuredLines(doc: NoticeDocument, extracted: ExtractedLicense[]): string[] {
  const { blocks } = buildLicenseBlocks(doc.packages, extracted);
  const lines: string[] = [
    doc.title,
    "=".repeat(Math.min(doc.title.length, 72)),
    "",
    "This product includes open source software components listed below. The full license texts are reproduced in the Licenses section.",
    "",
    "Components",
    "-".repeat(40),
  ];

  for (const pkg of componentsRows(doc)) {
    lines.push(`${pkg.name}  ${pkg.version}`);
    lines.push(`  License: ${pkg.licenseSpdx ?? "(unknown)"}`);
    if (pkg.copyright) {
      lines.push(`  Copyright: ${pkg.copyright}`);
    }
    lines.push("");
  }

  lines.push("Licenses", "-".repeat(40));
  for (const block of blocks) {
    lines.push(`${block.heading} (${block.licenseId})`);
    lines.push(`Used by: ${block.usedBy.join(", ")}`);
    lines.push("");
    lines.push(block.text ?? "(License text not available offline.)");
    lines.push("-".repeat(40));
    lines.push("");
  }

  lines.push(...onotFooterLines());
  return lines;
}

const PAGE_HEIGHT = 792;
const LINE_HEIGHT = 14;
const TOP = 760;
const BOTTOM = 56;
const LEFT = 48;
const MAX_CHARS = 90;

function paginate(lines: string[]): string[][] {
  const maxLines = Math.floor((TOP - BOTTOM) / LINE_HEIGHT);
  const pages: string[][] = [];
  let current: string[] = [];
  for (const raw of lines) {
    for (const line of wrapLines(raw, MAX_CHARS)) {
      if (current.length >= maxLines) {
        pages.push(current);
        current = [];
      }
      current.push(line);
    }
  }
  if (current.length > 0) {
    pages.push(current);
  }
  return pages.length > 0 ? pages : [[]];
}

function buildPageStream(pageLines: string[], pageNumber: number, pageCount: number): string {
  const commands: string[] = ["BT", "/F1 11 Tf", `${LEFT} ${TOP} Td`];
  let first = true;
  for (const line of pageLines) {
    if (!first) {
      commands.push(`0 ${-LINE_HEIGHT} Td`);
    }
    commands.push(`(${escapePdfText(line)}) Tj`);
    first = false;
  }
  commands.push(`0 ${BOTTOM - TOP + LINE_HEIGHT * (pageLines.length + 1)} Td`);
  commands.push(`/F1 9 Tf (${escapePdfText(`Page ${pageNumber} of ${pageCount}`)}) Tj`);
  commands.push(`0 -12 Td (${escapePdfText(`Generated by s2j-oss-notice ${TOOL_VERSION}`)}) Tj`);
  commands.push("ET");
  return commands.join("\n");
}

export function renderOnotPdf(doc: NoticeDocument, extracted: ExtractedLicense[]): Uint8Array {
  const pages = paginate(buildStructuredLines(doc, extracted));
  const pageCount = pages.length;

  const objects: string[] = [];
  const catalogIndex = objects.length;
  objects.push("");
  const pagesIndex = objects.length;
  objects.push("");
  const fontIndex = objects.length;
  objects.push("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");

  const pageIndices: number[] = [];
  const contentIndices: number[] = [];
  for (let i = 0; i < pageCount; i += 1) {
    pageIndices.push(objects.length);
    objects.push("");
    contentIndices.push(objects.length);
    const stream = buildPageStream(pages[i]!, i + 1, pageCount);
    const streamLen = Buffer.byteLength(stream, "utf8");
    objects.push(`<< /Length ${streamLen} >>\nstream\n${stream}\nendstream`);
  }

  const kids = pageIndices.map((index) => `${index + 1} 0 R`).join(" ");
  objects[pagesIndex] = `<< /Type /Pages /Kids [${kids}] /Count ${pageCount} >>`;
  objects[catalogIndex] = `<< /Type /Catalog /Pages ${pagesIndex + 1} 0 R >>`;

  for (let i = 0; i < pageCount; i += 1) {
    const pageIndex = pageIndices[i]!;
    const contentIndex = contentIndices[i]!;
    objects[pageIndex] =
      `<< /Type /Page /Parent ${pagesIndex + 1} 0 R /MediaBox [0 0 612 ${PAGE_HEIGHT}] /Contents ${contentIndex + 1} 0 R /Resources << /Font << /F1 ${fontIndex + 1} 0 R >> >> >>`;
  }

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [0];
  for (let i = 0; i < objects.length; i += 1) {
    offsets.push(Buffer.byteLength(pdf, "utf8"));
    pdf += `${i + 1} 0 obj\n${objects[i]}\nendobj\n`;
  }

  const xrefStart = Buffer.byteLength(pdf, "utf8");
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (let i = 1; i < offsets.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogIndex + 1} 0 R >>\n`;
  pdf += `startxref\n${xrefStart}\n%%EOF\n`;

  return new TextEncoder().encode(pdf);
}