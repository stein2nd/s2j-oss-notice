import { TOOL_VERSION } from "../../compat/tool-version.js";
import type { ExtractedLicense, NoticeDocument } from "../../types/notice.js";
import { buildLicenseBlocks, componentsRows } from "../onot-shared/licenses.js";

function escapeTableCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}

function componentsTable(doc: NoticeDocument): string {
  const lines = [
    "| Name | Version | License | Copyright |",
    "|---|---|---|---|",
    ...componentsRows(doc).map((pkg) => {
      const license = pkg.licenseSpdx ?? "(unknown)";
      const copyright = pkg.copyright ?? "";
      return `| ${escapeTableCell(pkg.name)} | ${escapeTableCell(pkg.version)} | ${escapeTableCell(license)} | ${escapeTableCell(copyright)} |`;
    }),
  ];
  return lines.join("\n");
}

function licensesMarkdown(blocks: ReturnType<typeof buildLicenseBlocks>["blocks"]): string {
  const parts: string[] = [];
  for (const block of blocks) {
    parts.push(`### ${block.heading} (\`${block.licenseId}\`)`);
    parts.push(`Used by: ${block.usedBy.join(", ")}`);
    parts.push("");
    parts.push("```text");
    for (const line of (block.text ?? "(License text not available offline.)").split(/\n/)) {
      parts.push(line);
    }
    parts.push("```");
  }
  if (parts.length === 0) {
    return "_No license entries were generated._";
  }
  return parts.join("\n").trimEnd();
}

export type RenderMarkdownResult = {
  content: string;
  warnings: string[];
};

export function renderOnotMarkdown(
  doc: NoticeDocument,
  extractedLicenses: ExtractedLicense[],
): RenderMarkdownResult {
  const { blocks, warnings: licenseWarnings } = buildLicenseBlocks(doc.packages, extractedLicenses);

  const parts = [
    `# ${doc.title}`,
    "",
    "This product includes open source software components listed below. The full license texts are reproduced in the Licenses section.",
    "",
    "## Components",
    "",
    componentsTable(doc),
    "",
    "## Licenses",
    licensesMarkdown(blocks),
    "",
    "## Offer of Source Code",
    "",
    "This product contains open source software. Where required by the applicable license, you may obtain the corresponding source code.",
    "",
    `Generated by s2j-oss-notice ${TOOL_VERSION}.`,
    "",
  ];

  return {
    content: parts.join("\n"),
    warnings: [...doc.warnings, ...licenseWarnings],
  };
}