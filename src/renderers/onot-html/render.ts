import { TOOL_VERSION } from "../../compat/tool-version.js";
import type { ExtractedLicense, NoticeDocument } from "../../types/notice.js";
import { buildLicenseBlocks, componentsRows } from "../onot-shared/licenses.js";

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function renderOnotHtml(doc: NoticeDocument, extracted: ExtractedLicense[]): string {
  const { blocks } = buildLicenseBlocks(doc.packages, extracted);
  const rows = componentsRows(doc)
    .map(
      (pkg) =>
        `<tr><td>${escapeHtml(pkg.name)}</td><td>${escapeHtml(pkg.version)}</td><td>${escapeHtml(pkg.licenseSpdx ?? "(unknown)")}</td><td>${escapeHtml(pkg.copyright ?? "")}</td></tr>`,
    )
    .join("\n");

  const licenseSections = blocks
    .map((block) => {
      const body = escapeHtml(block.text ?? "(License text not available offline.)");
      return `<h3>${escapeHtml(block.heading)} (<code>${escapeHtml(block.licenseId)}</code>)</h3>
<p>Used by: ${escapeHtml(block.usedBy.join(", "))}</p>
<pre>${body}</pre>`;
    })
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>${escapeHtml(doc.title)}</title>
</head>
<body>
<h1>${escapeHtml(doc.title)}</h1>
<p>This product includes open source software components listed below. The full license texts are reproduced in the Licenses section.</p>
<h2>Components</h2>
<table>
<thead><tr><th>Name</th><th>Version</th><th>License</th><th>Copyright</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>
<h2>Licenses</h2>
${licenseSections || "<p><em>No license entries were generated.</em></p>"}
<h2 id="offer">Offer of Source Code</h2>
<p>This product contains open source software. Where required by the applicable license, you may obtain the corresponding source code.</p>
<p class="generator">Generated by s2j-oss-notice ${escapeHtml(TOOL_VERSION)}.</p>
</body>
</html>
`;
}