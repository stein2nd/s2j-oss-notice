/**
 * Normalize Notice Markdown before golden / onot diff (semantic equivalence).
 */
export function normalizeNoticeMarkdown(markdown: string): string {
  return (
    markdown
      .replace(/\r\n/g, "\n")
      .replace(/Generated by (?:onot|s2j-oss-notice) [^\n]+\n?/g, "Generated by onot 0.0.0-test.\n")
      .replace(/[ \t]+$/gm, "")
      .replace(/\n+```/g, "\n\n```")
      .trimEnd() + "\n"
  );
}